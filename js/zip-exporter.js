/**
 * RenderX Image Studio - ZIP & Timeline Sync Exporter
 * Bundles generated images with timeline-based naming and generates CapCut/Premiere CSV sync sheets.
 */

class ZipExporter {
  /**
   * Export batch of images to a structured ZIP file
   * @param {Array<Object>} items - List of generated image records
   * @param {string} [archiveName] - Base name for the zip file
   * @returns {Promise<Blob>}
   */
  static async export(items, archiveName = 'RenderX_Timeline_Images.zip') {
    if (!items || items.length === 0) {
      throw new Error('No generated images available to export.');
    }

    const zip = new window.SimpleZip();

    // CSV Header for video editors (CapCut, Premiere Pro, DaVinci Resolve)
    let csvContent = 'Index,Filename,Timestamp,Start (s),End (s),Prompt\n';

    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      if (!item.blob) continue;

      // Extract start and end seconds
      let startSec = '';
      let endSec = '';
      if (item.timestamp) {
        const parts = item.timestamp.split(/[-–—to]+/i);
        if (parts.length === 2) {
          startSec = parts[0].trim().replace(/[^0-9.]/g, '');
          endSec = parts[1].trim().replace(/[^0-9.]/g, '');
        }
      }

      // Add image file to ZIP
      const filename = item.filename || window.TimelineParser.generateFilename(item.index, item.cleanTimestamp);
      await zip.file(filename, item.blob);

      // Append CSV row
      const escapedPrompt = (item.prompt || '').replace(/"/g, '""');
      csvContent += `${item.index},"${filename}","${item.timestamp || ''}","${startSec}","${endSec}","${escapedPrompt}"\n`;
    }

    // Add Timeline Sync CSV file
    await zip.file('timeline_sync.csv', csvContent);

    // Add Video Editor Guide
    const guideContent = `========================================================
RenderX Image Studio - Video Editor Timeline Guide
========================================================
Total Scenes Generated: ${items.length}

HOW TO USE IN CAPCUT / PREMIERE PRO / DAVINCI RESOLVE:
1. Extract all images to your project folder.
2. The filenames follow your exact timeline order:
   e.g. "01. 0-0.5.png" corresponds to 0.0s to 0.5s in your voiceover.
3. Refer to 'timeline_sync.csv' for the exact duration of each image clip.
4. Drag and drop all images directly into your editing software timeline!

Generated by RenderX Image Studio v1.0.0
`;
    await zip.file('README_VIDEO_EDITORS.txt', guideContent);

    // Generate ZIP
    const zipBlob = zip.generate();

    // Trigger download in browser
    const downloadUrl = URL.createObjectURL(zipBlob);
    const link = document.createElement('a');
    link.href = downloadUrl;
    link.download = archiveName;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    setTimeout(() => URL.revokeObjectURL(downloadUrl), 5000);

    return zipBlob;
  }
}

// Global export
window.ZipExporter = ZipExporter;
